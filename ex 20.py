n_semana=int(input("Digite um número da semana"))
if n_semana ==1:
    print("Domingo")
elif n_semana ==2:
    print("Segunda")
elif n_semana ==3:
    print("Terça")
elif n_semana ==4:
    print("Quarta")
elif n_semana ==5:
    print("Quinta")
elif n_semana ==6:
    print("Sexta")
elif n_semana ==7:
    print("Sábado")
else:
    print("Esse número da semana não existe, Tente um número entre 1 a 7.")
